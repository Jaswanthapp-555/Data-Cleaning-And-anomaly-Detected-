"""PDF report renderer — generates valid PDF binary from the HTML report."""
import io
import re
import logging

logger = logging.getLogger(__name__)


def render_pdf_report(html_content: str) -> bytes:
    """Convert HTML report to valid PDF bytes using xhtml2pdf with robust ReportLab fallback."""
    # 1. Clean HTML for PDF rendering:
    # Completely strip any external @import and @font-face rules that cause network or permission errors
    clean_html = re.sub(r"@import\s+(?:url\([^)]*\)|[^\n;]+)\s*;?", "", html_content, flags=re.IGNORECASE)
    clean_html = re.sub(r"@font-face\s*\{[^}]*\}", "", clean_html, flags=re.IGNORECASE)
    clean_html = re.sub(r"<link[^>]+rel=[\"']stylesheet[\"'][^>]*>", "", clean_html, flags=re.IGNORECASE)
    clean_html = re.sub(r"font-family:\s*[^;]+;", "font-family: Helvetica, Arial, sans-serif;", clean_html, flags=re.IGNORECASE)

    # 2. Try xhtml2pdf (pisa)
    try:
        from xhtml2pdf import pisa
        out = io.BytesIO()
        status = pisa.CreatePDF(clean_html, dest=out, encoding="utf-8")
        pdf_bytes = out.getvalue()
        # Even if status.err has non-fatal CSS warnings, verify if valid PDF binary was written
        if pdf_bytes and pdf_bytes.startswith(b"%PDF") and (b"%%EOF" in pdf_bytes) and len(pdf_bytes) > 500:
            return pdf_bytes
    except Exception as e:
        logger.warning(f"xhtml2pdf error: {e}")

    # 3. Guaranteed valid PDF fallback using ReportLab Platypus
    return _build_reportlab_fallback(html_content)


def _build_reportlab_fallback(html_content: str) -> bytes:
    """Fallback to generating a complete, valid PDF document using ReportLab."""
    try:
        from reportlab.lib.pagesizes import letter
        from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, HRFlowable
        from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
        from reportlab.lib import colors
        import html as html_lib

        buf = io.BytesIO()
        doc = SimpleDocTemplate(
            buf,
            pagesize=letter,
            leftMargin=36,
            rightMargin=36,
            topMargin=36,
            bottomMargin=36
        )
        styles = getSampleStyleSheet()
        story = []

        title_style = ParagraphStyle(
            "DocTitle",
            parent=styles["Heading1"],
            fontSize=20,
            leading=24,
            textColor=colors.HexColor("#0f172a"),
            fontName="Helvetica-Bold",
            spaceAfter=6,
        )
        sub_style = ParagraphStyle(
            "DocSub",
            parent=styles["Normal"],
            fontSize=9,
            leading=12,
            textColor=colors.HexColor("#64748b"),
            fontName="Helvetica",
            spaceAfter=12,
        )
        heading_style = ParagraphStyle(
            "SectionHeading",
            parent=styles["Heading2"],
            fontSize=13,
            leading=16,
            textColor=colors.HexColor("#1e293b"),
            fontName="Helvetica-Bold",
            spaceBefore=10,
            spaceAfter=6,
        )
        body_style = ParagraphStyle(
            "DocBody",
            parent=styles["Normal"],
            fontSize=9.5,
            leading=13.5,
            textColor=colors.HexColor("#334155"),
            fontName="Helvetica",
            spaceAfter=6,
        )

        story.append(Paragraph("CleanCore Data Quality & Profiling Report", title_style))
        story.append(Paragraph("Generated by Automated Data Quality & Anomaly Profiler", sub_style))
        story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#cbd5e1"), spaceAfter=14))

        # Extract headings and text from HTML
        plain_text = re.sub(r"<script[^>]*>[\s\S]*?</script>", "", html_content, flags=re.IGNORECASE)
        plain_text = re.sub(r"<style[^>]*>[\s\S]*?</style>", "", plain_text, flags=re.IGNORECASE)
        plain_text = re.sub(r"<[^>]+>", "\n", plain_text)
        lines = [html_lib.unescape(line.strip()) for line in plain_text.splitlines() if line.strip()]

        for line in lines[:200]:  # Cap lines
            if len(line) < 60 and any(keyword in line.lower() for keyword in ["overview", "summary", "quality", "drift", "schema", "issues", "statistics", "dataset"]):
                story.append(Paragraph(line, heading_style))
            else:
                story.append(Paragraph(line, body_style))

        doc.build(story)
        pdf_bytes = buf.getvalue()
        if pdf_bytes and pdf_bytes.startswith(b"%PDF"):
            return pdf_bytes
    except Exception as e:
        logger.error(f"ReportLab fallback error: {e}")

    # Bare minimal valid PDF 1.4 document with catalog and empty page
    from reportlab.pdfgen import canvas
    buf = io.BytesIO()
    c = canvas.Canvas(buf, pagesize=(612, 792))
    c.setFont("Helvetica-Bold", 16)
    c.drawString(72, 720, "CleanCore Data Quality Report")
    c.setFont("Helvetica", 10)
    c.drawString(72, 690, "The requested report was compiled. Please view the interactive HTML version for full charts.")
    c.showPage()
    c.save()
    return buf.getvalue()
